// The Markdown report a validation run writes into the pull request body. Pure: the results, the
// violations and the attempt count come in, the text goes out. Time, ids and I/O stay with the caller.

import type { CommandResult, DiffViolation } from './validation-policy'

export type ValidationReportInput = {
  results: CommandResult[]
  violations: DiffViolation[]
  /** Runs the loop used. The first run is 1. */
  attempts: number
  outcome: 'passed' | 'failed'
}

/** The whole report, overhead included. Past this the oldest output lines are dropped. */
const REPORT_CAP = 60 * 1024
/** Output lines kept per failing command: the end is where a failure is reported. */
const TAIL_LINES = 20
const NO_OUTPUT = '(no output)'
const CUT_OUTPUT = '(output cut to fit the report)'
const TRUNCATED = '\n[report truncated]'

type OutputBlock = { name: string; original: number; lines: string[] }

const isFailing = (result: CommandResult): boolean => result.exitCode !== 0 || result.timedOut

/** The last lines of an output, oldest first. */
function tailLines(outputTail: string): string[] {
  const trimmed = outputTail.replace(/\s+$/, '')
  return trimmed === '' ? [] : trimmed.split('\n').slice(-TAIL_LINES)
}

/** A fence longer than any run of backticks it contains, so output cannot close it early. */
function fenceFor(lines: readonly string[]): string {
  const runs = lines.join('\n').match(/`+/g) ?? []
  return '`'.repeat(Math.max(3, ...runs.map((run) => run.length + 1)))
}

/** A table cell must not end its column. */
function cell(text: string): string {
  return text.replaceAll('\\', '\\\\').replaceAll('|', '\\|').replaceAll(/\r?\n/g, ' ')
}

function describeViolation(violation: DiffViolation): string {
  return violation.path === undefined
    ? `${violation.rule}: ${violation.detail}`
    : `${violation.rule} (${violation.path}): ${violation.detail}`
}

function render(input: ValidationReportInput, blocks: readonly OutputBlock[]): string {
  const attempts = `${input.attempts} attempt${input.attempts === 1 ? '' : 's'}`
  const lines = ['## Validation', '', `Validation ${input.outcome} after ${attempts}.`, '']

  if (input.results.length === 0) {
    lines.push('No commands ran.', '')
  } else {
    lines.push('| Command | Exit code | Timed out |', '| --- | --- | --- |')
    for (const result of input.results) {
      lines.push(`| ${cell(result.name)} | ${result.exitCode} | ${result.timedOut ? 'yes' : 'no'} |`)
    }
    lines.push('')
  }

  for (const block of blocks) {
    lines.push(`### ${cell(block.name)}`, '')
    if (block.lines.length === 0) {
      lines.push(block.original === 0 ? NO_OUTPUT : CUT_OUTPUT, '')
      continue
    }
    if (block.lines.length < block.original) lines.push(CUT_OUTPUT, '')
    const fence = fenceFor(block.lines)
    lines.push(fence, ...block.lines, fence, '')
  }

  if (input.violations.length > 0) {
    lines.push(
      '### Diff violations',
      '',
      ...input.violations.map((violation) => `- ${describeViolation(violation)}`),
      '',
    )
  }

  lines.push('Generated by steward.')
  return lines.join('\n')
}

/**
 * Renders the report for the pull request body: the outcome, one row per command, the tail of each
 * failing command in a fence it cannot break out of, and the diff violations. The report stays under
 * 60 KB; the oldest output lines go first, since the end of a command's output is where a failure is.
 */
export function renderValidationReport(input: ValidationReportInput): string {
  const blocks: OutputBlock[] = input.results.filter(isFailing).map((result) => {
    const lines = tailLines(result.outputTail)
    return { name: result.name, original: lines.length, lines: [...lines] }
  })

  let text = render(input, blocks)
  while (text.length > REPORT_CAP) {
    const oldest = blocks.find((block) => block.lines.length > 0)
    if (oldest === undefined) break
    oldest.lines.shift()
    text = render(input, blocks)
  }

  return text.length <= REPORT_CAP ? text : `${text.slice(0, REPORT_CAP - TRUNCATED.length)}${TRUNCATED}`
}
