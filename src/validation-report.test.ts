import { describe, expect, it } from 'vitest'

import type { CommandResult, DiffViolation } from './validation-policy'
import { renderValidationReport } from './validation-report'

const CAP = 60 * 1024
const ok = (name: string): CommandResult => ({ name, exitCode: 0, timedOut: false, outputTail: 'fine\n' })
const bad = (name: string, outputTail = 'boom\n'): CommandResult => ({ name, exitCode: 1, timedOut: false, outputTail })
const report = (
  results: CommandResult[],
  violations: DiffViolation[] = [],
  attempts = 1,
  outcome: 'passed' | 'failed' = 'passed',
): string => renderValidationReport({ results, violations, attempts, outcome })

/** The lines inside a fenced block. The backreference needs the same fence length to close it. */
function block(text: string): string[] {
  const match = /^(`{3,})\n([\s\S]*?)\n\1$/m.exec(text)
  if (match === null) throw new Error(`no fenced block in:\n${text}`)
  return match[2].split('\n')
}

describe('renderValidationReport', () => {
  it('reports a pass with a table of every command and the footer last', () => {
    const text = report([ok('node'), ok('test')])

    expect(text).toContain('## Validation')
    expect(text).toContain('Validation passed after 1 attempt.')
    expect(text).toContain('| Command | Exit code | Timed out |')
    expect(text).toContain('| node | 0 | no |')
    expect(text).toContain('| test | 0 | no |')
    expect(text.trimEnd().endsWith('Generated by steward.')).toBe(true)
    expect(text.match(/^`{3,}$/gm)).toBeNull()
  })

  it('reports a failure with the last 20 lines of each failing command', () => {
    const output = Array.from({ length: 25 }, (_, index) => `line ${index + 1}`).join('\n')
    const text = report(
      [ok('node'), bad('test', output), { name: 'slow', exitCode: 137, timedOut: true, outputTail: '' }],
      [],
      2,
      'failed',
    )

    expect(text).toContain('Validation failed after 2 attempts.')
    expect(text).toContain('| test | 1 | no |')
    expect(text).toContain('| slow | 137 | yes |')
    expect(block(text)).toEqual(Array.from({ length: 20 }, (_, index) => `line ${index + 6}`))
    expect(text).not.toContain('line 5')
    expect(text).toContain('(no output)')
  })

  it('lists the violations and says when no command ran', () => {
    const violations: DiffViolation[] = [
      { rule: 'forbidden-path', path: '.env', detail: '.env is a forbidden path' },
      { rule: 'too-large', detail: '900 changed lines, the limit is 800' },
    ]
    const text = report([], violations, 1, 'failed')

    expect(text).toContain('Validation failed after 1 attempt.')
    expect(text).toContain('No commands ran.')
    expect(text).toContain('### Diff violations')
    expect(text).toContain('- forbidden-path (.env): .env is a forbidden path')
    expect(text).toContain('- too-large: 900 changed lines, the limit is 800')
  })

  it('stays under 60 KB, cutting the oldest output first', () => {
    const first = Array.from({ length: 20 }, (_, index) => `first-${index + 1} ${'x'.repeat(4000)}`).join('\n')
    const second = Array.from({ length: 20 }, (_, index) => `second-${index + 1}`).join('\n')
    const text = report([bad('first', first), bad('second', second)], [], 1, 'failed')

    expect(text.length).toBeLessThanOrEqual(CAP)
    expect(text).not.toContain('first-1 ')
    expect(text).toContain('(output cut to fit the report)')
    for (let line = 1; line <= 20; line++) expect(text).toContain(`second-${line}`)
    expect(text.trimEnd().endsWith('Generated by steward.')).toBe(true)
  })

  it('uses a fence longer than any run of backticks in the output', () => {
    const text = report([bad('test', 'before\n```\nafter\n````\nstill inside\nend')])

    expect(text.match(/^`{5,}$/gm)).toEqual(['`````', '`````'])
    expect(block(text)).toEqual(['before', '```', 'after', '````', 'still inside', 'end'])
  })
})
